create extension if not exists pgcrypto;

create table if not exists public.bot_members (
 id uuid primary key default gen_random_uuid(),
 guild_id text not null,
 discord_user_id text not null,
 username text not null default 'unknown',
 display_name text not null default 'unknown',
 avatar_url text,
 first_seen_at timestamptz not null default now(),
 last_seen_at timestamptz not null default now(),
 message_count bigint not null default 0,
 xp bigint not null default 0,
 level integer not null default 0,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique(guild_id,discord_user_id)
);
create table if not exists public.bot_settings (
 id uuid primary key default gen_random_uuid(),
 guild_id text not null,
 key text not null,
 value text not null,
 updated_at timestamptz not null default now(),
 unique(guild_id,key)
);
create table if not exists public.bot_events (
 id bigint generated by default as identity primary key,
 guild_id text not null,
 discord_user_id text,
 event_type text not null,
 data jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create index if not exists bot_events_guild_created_idx on public.bot_events(guild_id,created_at desc);
create table if not exists public.bot_warnings (
 id uuid primary key default gen_random_uuid(),
 guild_id text not null,
 discord_user_id text not null,
 moderator_id text not null,
 reason text not null,
 created_at timestamptz not null default now()
);
create index if not exists bot_warnings_lookup_idx on public.bot_warnings(guild_id,discord_user_id,created_at desc);
create table if not exists public.bot_tickets (
 id uuid primary key default gen_random_uuid(),
 guild_id text not null,
 channel_id text,
 discord_user_id text not null,
 subject text not null,
 details text not null,
 status text not null default 'open' check(status in ('open','closed')),
 created_at timestamptz not null default now(),
 closed_at timestamptz
);
create table if not exists public.bot_suggestions (
 id uuid primary key default gen_random_uuid(),
 guild_id text not null,
 discord_user_id text not null,
 title text not null,
 details text not null,
 status text not null default 'pending' check(status in ('pending','approved','denied')),
 message_id text,
 created_at timestamptz not null default now(),
 reviewed_by text,
 review_note text
);
create table if not exists public.bot_polls (
 id uuid primary key default gen_random_uuid(),
 guild_id text not null,
 discord_user_id text not null,
 question text not null,
 options jsonb not null,
 message_id text,
 created_at timestamptz not null default now()
);
create table if not exists public.bot_forms (
 id uuid primary key default gen_random_uuid(),
 guild_id text not null,
 discord_user_id text not null,
 form_type text not null,
 title text not null,
 answers jsonb not null default '{}'::jsonb,
 status text not null default 'submitted',
 created_at timestamptz not null default now(),
 reviewed_by text,
 review_note text
);
create table if not exists public.bot_accounts (
 id uuid primary key default gen_random_uuid(),
 discord_user_id text not null unique,
 username text not null unique,
 password_hash text not null,
 created_at timestamptz not null default now(),
 last_login_at timestamptz
);
create table if not exists public.bot_rank_roles (
 id uuid primary key default gen_random_uuid(),
 guild_id text not null,
 level integer not null,
 role_id text not null,
 unique(guild_id,level)
);

alter table public.bot_members enable row level security;
alter table public.bot_settings enable row level security;
alter table public.bot_events enable row level security;
alter table public.bot_warnings enable row level security;
alter table public.bot_tickets enable row level security;
alter table public.bot_suggestions enable row level security;
alter table public.bot_polls enable row level security;
alter table public.bot_forms enable row level security;
alter table public.bot_accounts enable row level security;
alter table public.bot_rank_roles enable row level security;

revoke all on public.bot_members,public.bot_settings,public.bot_events,public.bot_warnings,public.bot_tickets,public.bot_suggestions,public.bot_polls,public.bot_forms,public.bot_accounts,public.bot_rank_roles from anon,authenticated;
grant all on public.bot_members,public.bot_settings,public.bot_events,public.bot_warnings,public.bot_tickets,public.bot_suggestions,public.bot_polls,public.bot_forms,public.bot_accounts,public.bot_rank_roles to service_role;
grant usage,select on all sequences in schema public to service_role;
